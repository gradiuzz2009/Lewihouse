package com.example.data.language

import java.text.NumberFormat
import java.util.Locale

enum class AppLanguage(val code: String, val label: String) {
    EN("en", "English"),
    ID("id", "Bahasa Indonesia")
}

object LanguageManager {
    fun getStrings(language: AppLanguage): StringsDict {
        return when (language) {
            AppLanguage.EN -> EnglishStrings
            AppLanguage.ID -> IndonesianStrings
        }
    }

    fun formatCurrency(amount: Double, language: AppLanguage = AppLanguage.ID): String {
        val locale = if (language == AppLanguage.ID) Locale("in", "ID") else Locale.US
        val formatter = NumberFormat.getNumberInstance(locale)
        val formattedNumber = formatter.format(amount.toLong())
        return if (language == AppLanguage.ID) {
            "Rp $formattedNumber"
        } else {
            "IDR $formattedNumber"
        }
    }

    fun formatKwh(kwh: Double): String {
        return String.format(Locale.US, "%.1f kWh", kwh)
    }
}

