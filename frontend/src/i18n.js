export function LangProvider({ children }) {
  const [lang, setLangState] = useState(localStorage.getItem("lh_lang") || "id");
  const setLang = (l) => {
    localStorage.setItem("lh_lang", l);
    setLangState(l);
  };
  const t = (key, vars) => {
    let s = dict[lang]?.[key] ?? dict.id[key] ?? key;
    if (vars) Object.entries(vars).forEach(([k, v]) => (s = s.replace(`{${k}}`, v)));
    return s;
  };
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);

export function LangToggle({ dark }) {
  const { lang, setLang } = useLang();
  return (
    <button
      onClick={() => setLang(lang === "id" ? "en" : "id")}
      data-testid="lang-toggle"
      className={`h-9 px-3 rounded-full text-[11px] font-bold tracking-widest active:scale-95 transition-transform ${
        dark ? "bg-white/10 border border-white/20 text-white" : "bg-muted text-primary"
      }`}
    >
      {lang === "id" ? "EN" : "ID"}
    </button>
  );
}
